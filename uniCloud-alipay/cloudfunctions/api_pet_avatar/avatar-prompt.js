'use strict';

const MAX_PROMPT_CHARS = 5000;

function buildAvatarPrompt(sourceCount) {
	const count = Number(sourceCount);
	if (!Number.isInteger(count) || count < 1 || count > 3) {
		const error = new Error('INVALID_SOURCE_COUNT');
		error.code = 'INVALID_SOURCE_COUNT';
		throw error;
	}

	const prompt = `"请根据上传图片生成“用户真实宠物”的专属电子宠物主形象，用于宠物 App 首页、档案页和长期展示。

【最重要规则：严格区分图片角色】

第1张图 = 官方风格参考图。
它只负责定义以下内容：
- 整体画风
- 3D质感
- 渲染精度
- 光线氛围
- 干净背景
- 构图方式
- 主体占比
- 柔和高级感
- 写实与轻微角色化之间的程度

第1张图绝对不负责定义以下内容：
- 宠物物种
- 品种
- 毛色
- 花纹
- 眼睛颜色
- 脸型
- 耳朵形状
- 身体结构
- 毛发长短
- 尾巴形态
- 任何具体身份特征

再次强调：
第1张图只是“风格模板”，不是“身份模板”。
绝对禁止把第1张图里的宠物直接生成出来。
如果最终结果长得像第1张图里的宠物，而不像后面真实照片里的宠物，则本次生成视为失败。

第2张及之后所有图片 = 同一只用户真实宠物的身份参考图。
最终生成的宠物是谁、长什么样，必须只由第2张及之后的真实照片决定。

【核心任务】

你的首要目标不是做一只泛泛可爱的宠物，而是让主人一眼认出：
“这就是我家的宠物。”

优先级必须是：
1. 像这只宠物
2. 特征准确
3. 风格统一
4. 干净好看
5. 温柔可爱

【输入托底要求】

用户上传的宠物照片可能很普通，甚至有：
- 背景杂乱
- 光线不好
- 角度随意
- 遮挡
- 模糊
- 色偏
- 闪光灯
- 没看镜头
- 不是标准姿势

这些都属于正常输入。
不要要求用户重新拍摄。
你必须主动从普通生活照片中提取宠物最稳定、最真实的身份特征。

【必须忽略的内容】

忽略所有与宠物身份无关的元素：
背景、家具、地板、墙面、沙发、床、窗户、玩具、食盆、水盆、猫窝狗窝、笼子、电线、枕头、毯子、人的手脚身体、其他动物、阴影、反光、滤镜、文字、水印、贴纸、UI界面、杂物。

这些东西绝不能变成宠物的毛色、花纹、身体细节或道具。

【身份提取规则】

请从第2张及之后的照片中，优先提取并保留：
- 真实物种
- 体型比例
- 脸型与五官比例
- 眼睛颜色
- 耳朵形状
- 毛发长短与蓬松度
- 主毛色
- 次毛色
- 花纹类型
- 花纹分布位置
- 胸口、腹部、四肢、尾巴的颜色特征
- 尾巴长度、粗细、毛量和颜色
- 明显且稳定的个体特征

如果有多张真实照片，请综合共同出现、最稳定、最清晰的特征，不要被单张照片的角度、阴影、偏色和局部模糊误导。

【禁止错误】

绝对禁止：
- 直接生成第1张风格图里的宠物
- 借用第1张图宠物的物种
- 借用第1张图宠物的毛色和花纹
- 借用第1张图宠物的眼睛颜色
- 借用第1张图宠物的脸型和比例
- 因为第1张图是猫，就把别的动物猫化
- 凭空增加原图没有的花纹、色块、条纹、斑点
- 凭空改变眼睛颜色
- 凭空改变品种感
- 多尾巴、多肢体、多耳朵、多爪子
- 项圈、衣服、蝴蝶结、饰品、道具
- 复杂背景
- 其他动物

如果某些细节看不清，宁可简化，也不要脑补。

【风格要求】

最终画面必须参考第1张图的“视觉风格”，但必须保留用户宠物自己的真实身份。

风格要求：
- 高保真 3D 电子宠物形象
- 干净、柔和、精致、自然
- 轻微角色化
- 轻微萌化，但要克制
- 不要大头Q版
- 不要超大眼睛
- 不要塑料玩具感
- 不要二维插画感
- 不要过度卡通化
- 不要变成完全写实摄影

整体感觉应为：
“真实宠物身份 + 统一官方高质感风格”。

【构图要求】

- 只生成一只宠物
- 方形画幅
- 全身或3/4全身
- 姿态自然稳定
- 正面或轻微3/4朝向
- 主体完整，不截断耳朵、尾巴、四肢
- 主体占画面约70%
- 干净浅色背景
- 柔和自然光线
- 轻微接地阴影
- 方便后续放入 App UI

【最终结果标准】

成功标准只有一个：
看起来明显是“第2张及之后那些真实照片里的同一只宠物”，
同时拥有“第1张图所定义的官方视觉风格”。

失败标准：
只要生成结果明显更像第1张图里的宠物，而不像后面真实照片里的宠物，就算失败，必须避免。"`;

	if (prompt.length > MAX_PROMPT_CHARS) {
		const error = new Error('PROMPT_TOO_LONG');
		error.code = 'PROMPT_TOO_LONG';
		throw error;
	}
	return prompt;
}

module.exports = {
	MAX_PROMPT_CHARS,
	buildAvatarPrompt
};
