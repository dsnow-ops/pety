function normalizeStage(stage) {
  return stage === 'deceased' ? 'deceased' : 'current';
}

function normalizeDate(date) {
  const candidate = date instanceof Date ? new Date(date.getTime()) : new Date(date || Date.now());
  return Number.isNaN(candidate.getTime()) ? new Date() : candidate;
}

function getLocalDayNumber(date) {
  return Math.floor(Date.UTC(
    date.getFullYear(),
    date.getMonth(),
    date.getDate()
  ) / 86400000);
}

function getStablePetOffset(petId, stage, poolLength) {
  const seed = `${String(petId || 'default-pet')}|${stage}`;
  let hash = 2166136261;

  for (let index = 0; index < seed.length; index += 1) {
    hash ^= seed.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }

  return (hash >>> 0) % poolLength;
}

export function getDailyHomeCopy({
  petId,
  petName,
  relationshipStage,
  date = new Date()
} = {}) {
  const stage = normalizeStage(relationshipStage);
  const pool = stage === 'deceased'
    ? DECEASED_HOME_DAILY_COPY
    : CURRENT_HOME_DAILY_COPY;
  const localDate = normalizeDate(date);
  const petOffset = getStablePetOffset(petId, stage, pool.length);
  const index = (petOffset + getLocalDayNumber(localDate)) % pool.length;
  const name = String(petName || '宝贝').trim().slice(0, 8) || '宝贝';

  return pool[index].replace(/\{name\}/g, name);
}
